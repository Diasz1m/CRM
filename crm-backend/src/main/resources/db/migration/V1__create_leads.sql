CREATE TABLE leads (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(150) NOT NULL,
    email varchar(254),
    phone varchar(40),
    source varchar(100),
    stage varchar(30) NOT NULL,
    next_action varchar(255),
    next_action_date date,
    created_at timestamp with time zone NOT NULL,
    version bigint NOT NULL,
    CONSTRAINT leads_contact_required CHECK (email IS NOT NULL OR phone IS NOT NULL),
    CONSTRAINT leads_stage_valid CHECK (
        stage IN ('NEW', 'CONTACTED', 'PROPOSAL_SENT', 'WON', 'LOST')
    )
);

CREATE INDEX leads_stage_id_idx ON leads (stage, id);
